import { describe, expect, it } from "vitest";
import { jsPDF } from "jspdf";
import { autoTable } from "jspdf-autotable";
import { zipSync, strToU8 } from "fflate";
import { parseFile, parseJsonText, ParseError } from "../src/engine/parse";
import { analyzeSheet } from "../src/engine/pipeline";
import { collect } from "../src/state/collect";
import { fileFrom } from "./helpers";

function tablePdf(rows: number): Buffer {
  const doc = new jsPDF();
  doc.text("Daily MIS — WhatsApp campaigns", 14, 14);
  const body = Array.from({ length: rows }, (_, i) => [`2026-10-${String((i % 28) + 1).padStart(2, "0")}`, i % 2 ? "Invoice Discounting" : "Asset Financing", `${(64087 + i * 13).toLocaleString("en-IN")}`, `${(60000 + i * 11).toLocaleString("en-IN")}`, `${(90 + (i % 9)).toFixed(1)}%`]);
  autoTable(doc, { startY: 20, head: [["Date", "Campaign", "Sent", "Delivered", "Delivery %"]], body, theme: "plain" });
  doc.text("Generated by vendor portal", 14, 285);
  return Buffer.from(doc.output("arraybuffer"));
}

describe("PDF tables", () => {
  it("rebuilds a multi-page table from a text PDF", async () => {
    const parsed = await parseFile(fileFrom("mis.pdf", tablePdf(80)));
    expect(parsed.kind).toBe("pdf");
    const s = parsed.sheets[0];
    expect(s.headers).toEqual(["Date", "Campaign", "Sent", "Delivered", "Delivery %"]);
    expect(s.rows.length).toBe(80); // repeated page headers are removed
    expect(s.rows[0]).toEqual(["2026-10-01", "Asset Financing", "64,087", "60,000", "90.0%"]);
    expect(s.rows[79][1]).toBe("Invoice Discounting");
    const rec = analyzeSheet(s, parsed);
    const sent = rec.schema.find((c) => c.name === "Sent")!;
    expect(["number", "currency"]).toContain(sent.type);
  });

  it("splits header labels that sit in one text run and treats 'Sr.' as a row number", async () => {
    const doc = new jsPDF();
    doc.setFont("courier", "normal");
    doc.setFontSize(9);
    const xCode = 110;
    const xBatch = xCode + doc.getTextWidth("process_code ");
    for (let page = 0; page < 2; page++) {
      if (page) doc.addPage();
      doc.text("Campaign Report", 80, 10);
      doc.text("Sr.", 10, 20);
      doc.text("Mobile_Number", 22, 20);
      doc.text("Upload Time", 60, 20);
      doc.text("process_code batch_id", xCode, 20); // one run covering two columns
      doc.text("Status", 165, 20);
      for (let i = 0; i < 30; i++) {
        const n = page * 30 + i + 1;
        const y = 26 + i * 6;
        doc.text(String(n), 10, y);
        doc.text(`91980000${String(n).padStart(4, "0")}`, 22, y);
        doc.text("22-10-2026 11:07", 60, y);
        doc.text(String(922634000 + n), xCode, y);
        doc.text(n % 2 ? "bma4gr5fqj" : "erjk4smtl8", xBatch, y);
        doc.text(n % 7 ? "Submitted" : "Failed", 165, y);
      }
    }
    const parsed = await parseFile(fileFrom("Campaign.pdf", Buffer.from(doc.output("arraybuffer"))));
    const s = parsed.sheets[0];
    expect(s.headers).toEqual(["Sr.", "Mobile_Number", "Upload Time", "process_code", "batch_id", "Status"]);
    expect(s.rows.length).toBe(60);
    expect(s.rows[59]).toEqual(["60", "919800000060", "22-10-2026 11:07", "922634060", "erjk4smtl8", "Submitted"]);
    const rec = analyzeSheet(s, parsed);
    expect(rec.schema.find((c) => c.name === "Sr.")?.role).toBe("identifier");
  });

  it("rejects PDFs without text and fake PDFs", async () => {
    const blank = new jsPDF();
    blank.rect(10, 10, 50, 50);
    await expect(parseFile(fileFrom("scan.pdf", Buffer.from(blank.output("arraybuffer"))))).rejects.toThrow(/scanned image/);
    await expect(parseFile(fileFrom("fake.pdf", "a,b\n1,2"))).rejects.toThrow(/real PDF/);
  });
});

describe("JSON", () => {
  it("reads records, nested objects and wrapped arrays", () => {
    const s = parseJsonText(JSON.stringify({ meta: { n: 2 }, data: [{ name: "A", stats: { sent: 10, opened: 2 } }, { name: "B", stats: { sent: 5 }, tags: ["x", "y"] }] }));
    expect(s.headers).toEqual(["name", "stats.sent", "stats.opened", "tags"]);
    expect(s.rows).toEqual([
      ["A", 10, 2, null],
      ["B", 5, null, "x, y"],
    ]);
  });

  it("explains JSON that has no records", async () => {
    await expect(parseFile(fileFrom("x.json", '{"a": 1}'))).rejects.toThrow(ParseError);
    await expect(parseFile(fileFrom("x.json", "{oops"))).rejects.toThrow(/can't be read/);
  });
});

describe("ZIP and folders", () => {
  const item = (name: string, data: Uint8Array | string, path = name, direct = true) => ({ file: new File([typeof data === "string" ? strToU8(data) : data], name), path, direct });

  it("unpacks nested ZIPs, skips junk and keeps readable files", async () => {
    const inner = zipSync({ "q3/leads.csv": strToU8("Lead,Amount\nA,10\nB,20\n") });
    const outer = zipSync({
      "sales.csv": strToU8("Region,Sales\nWest,5\n"),
      "report.pdf": new Uint8Array(tablePdf(5)),
      "photo.jpg": strToU8("not an image"),
      "__MACOSX/._sales.csv": strToU8("junk"),
      "archive/inner.zip": inner,
    });
    const c = await collect([item("data.zip", outer)]);
    expect(c.files.map((f) => f.name).sort()).toEqual(["data.zip › archive/inner.zip › q3/leads.csv", "data.zip › report.pdf", "data.zip › sales.csv"]);
    expect(c.skipped.flatMap((s) => s.names)).toEqual(["data.zip › photo.jpg"]);
    const parsed = await parseFile(c.files.find((f) => f.name.endsWith("leads.csv"))!);
    expect(parsed.sheets[0].name).toBe("leads");
    expect(parsed.sheets[0].rows.length).toBe(2);
  });

  it("keeps folder paths, ignores hidden files and reports damaged ZIPs", async () => {
    const c = await collect([
      item("a.csv", "x,y\n1,2\n", "Reports/a.csv", false),
      item(".DS_Store", "junk", "Reports/.DS_Store", false),
      item("notes.docx", "hi", "Reports/notes.docx", false),
      item("broken.zip", "PK not really"),
    ]);
    expect(c.files.map((f) => f.name)).toEqual(["Reports/a.csv"]);
    expect(c.skipped.map((s) => s.reason)).toEqual(expect.arrayContaining(["Not a spreadsheet, JSON or PDF", expect.stringMatching(/Couldn't open ZIP/)]));
  });
});
